export function assessmentLabels(
    messages: DialogMessages,
): ReadonlyMap<string, string> {
    const assessments = Object.entries(messages.assessments);
    const labels = new Map(assessments);
    for (const [code, label] of assessments) {
        labels.set(
            `${code}-rev`,
            messages.assessmentReview.replace("$1", label),
        );
    }
    return labels;
}
